'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const begin=html.indexOf('function resolveNetCollision(body){');
const end=html.indexOf('function tick(dt){',begin);
assert(begin>=0&&end>begin,'Net resolver must exist before the game loop');
const physics={W:800,netX:400,netHalf:7,netTop:262,ground:430};
vm.createContext(physics);
vm.runInContext(html.slice(begin,end),physics,{timeout:1000});
function collide(input){
 physics.input={r:36,...input};
 const hit=vm.runInContext('resolveNetCollision(input)',physics,{timeout:1000});
 return {hit,ball:physics.input};
}
const top=collide({x:400,y:225,vx:1,vy:5});
assert(top.hit,'Center-top impact should hit net');
assert(top.ball.vy<0,'Center-top impact should bounce upward');
assert(Math.abs(top.ball.vx-1)<.001,'A central hit should preserve sideways drift');
const right=collide({x:430,y:236,vx:-3,vy:5});
assert(right.hit,'Right top-edge collision should register');
assert(right.ball.vx>0&&right.ball.vy<0,'Right edge should rebound diagonally up-right');
const left=collide({x:370,y:236,vx:3,vy:5});
assert(left.hit,'Left top-edge collision should register');
assert(left.ball.vx<0&&left.ball.vy<0,'Left edge should rebound diagonally up-left');
const side=collide({x:359,y:300,vx:5,vy:.5});
assert(side.hit&&side.ball.vx<0,'Post side should reflect ball laterally');
const clear=collide({x:610,y:140,vx:-2,vy:6});
assert(!clear.hit&&clear.ball.vy===6,'Distant ball must not be deflected');
assert(html.includes('advanceBall(simulated,1)'),'CPU forecast must use swept net collisions');
assert(html.includes('advanceBall(ball,dt)'),'Real ball must use swept net collisions');
const speedTest={x:330,y:325,vx:155,vy:0,r:36};
physics.fastBall=speedTest;
vm.runInContext('advanceBall(fastBall,1)',physics,{timeout:1000});
assert(speedTest.x<400&&speedTest.vx<0,'Fast ball must rebound rather than tunnel through the net from the left');
const reverseTest={x:470,y:325,vx:-155,vy:0,r:36};
physics.fastBall=reverseTest;
vm.runInContext('advanceBall(fastBall,1)',physics,{timeout:1000});
assert(reverseTest.x>400&&reverseTest.vx>0,'Fast ball must rebound rather than tunnel through the net from the right');
const jump=html.match(/<button class="control" type="button" data-control="jump"[^>]*>([\s\S]*?)<\/button>/);
assert(jump,'Right-half jump control missing');
assert.equal(jump[1].trim(),'','Jump must have no visible arrow or icon');
assert(html.includes('left:50%!important;right:0!important;top:0!important;bottom:0!important;'),'Jump control must span from center to far right and full court height');
assert(html.includes('width:50%!important;height:100%!important;'),'Jump control must cover the entire right half');
assert(html.includes('body.fullscreen #controls [data-control=jump]'),'Fullscreen right-half touch control missing');
assert(html.includes('.stage .hud{z-index:5}'),'HUD buttons must remain accessible above jump surface');
console.log('Net-center, net-edge, post-side and full-right-court touch tests passed.');
